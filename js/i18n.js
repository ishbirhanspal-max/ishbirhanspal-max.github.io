class I18nEngine {
  static currentLang = 'en';

  static setLanguage(lang) {
    if (!I18N_TRANSLATIONS[lang]) lang = 'en';
    this.currentLang = lang;
    const t = I18N_TRANSLATIONS[lang];

    // Update Hero
    const heroTitle = document.querySelector('.hero-title');
    const heroSub = document.querySelector('.hero-subtitle');
    if (heroTitle) heroTitle.innerHTML = t.heroTitle;
    if (heroSub) heroSub.textContent = t.heroSubtitle;

    // Update Tab Labels
    const map = [
      { id: 'tabImageBtn', key: 'tabImage' },
      { id: 'tabBgBtn', key: 'tabBg' },
      { id: 'tabQrBtn', key: 'tabQr' },
      { id: 'tabBarcodeBtn', key: 'tabBarcode' },
      { id: 'tabPassportBtn', key: 'tabPassport' },
      { id: 'tabCollageBtn', key: 'tabCollage' },
      { id: 'tabFiltersBtn', key: 'tabFilters' },
      { id: 'tabSocialCropBtn', key: 'tabSocial' },
      { id: 'tabOcrBtn', key: 'tabOcr' },
      { id: 'tabVideoBtn', key: 'tabVideo' },
      { id: 'tabAudioBtn', key: 'tabAudio' },
      { id: 'tabPdfBtn', key: 'tabPdf' }
    ];

    map.forEach(({ id, key }) => {
      const el = document.getElementById(id);
      if (el && t[key]) {
        // preserve svg icon if present
        const svg = el.querySelector('svg');
        el.innerHTML = '';
        if (svg) el.appendChild(svg);
        el.appendChild(document.createTextNode(' ' + t[key]));
      }
    });

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }
}

window.I18nEngine = I18nEngine;
