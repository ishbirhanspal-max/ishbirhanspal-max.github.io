class I18nEngine {
  static currentLang = 'en';

  static setLanguage(lang) {
    if (!I18N_TRANSLATIONS[lang]) lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('optipixel_lang', lang);
    const t = I18N_TRANSLATIONS[lang];

    // Update Hero Title & Subtitle
    const heroTitle = document.querySelector('.hero-title');
    const heroSub = document.querySelector('.hero-subtitle');
    if (heroTitle && t.heroTitle) heroTitle.innerHTML = t.heroTitle;
    if (heroSub && t.heroSubtitle) heroSub.textContent = t.heroSubtitle;

    // Update Trust Badges
    const trustBadges = document.querySelectorAll('.trust-badges .badge-item span');
    if (trustBadges.length >= 3) {
      if (t.trustPrivate) trustBadges[0].textContent = t.trustPrivate;
      if (t.trustFast) trustBadges[1].textContent = t.trustFast;
      if (t.trustFree) trustBadges[2].textContent = t.trustFree;
    }

    // Update Tab Labels
    const tabMap = [
      { id: 'tabImageBtn', key: 'tabImage' },
      { id: 'tabBgBtn', key: 'tabBg' },
      { id: 'tabQrBtn', key: 'tabQr' },
      { id: 'tabBarcodeBtn', key: 'tabBarcode' },
      { id: 'tabPassportBtn', key: 'tabPassport' },
      { id: 'tabCollageBtn', key: 'tabCollage' },
      { id: 'tabFiltersBtn', key: 'tabFilters' },
      { id: 'tabSocialCropBtn', key: 'tabSocial' },
      { id: 'tabOcrBtn', key: 'tabOcr' },
      { id: 'tabVideoBtn', key: 'tabVideo' },
      { id: 'tabAudioBtn', key: 'tabAudio' },
      { id: 'tabPdfBtn', key: 'tabPdf' }
    ];

    tabMap.forEach(({ id, key }) => {
      const el = document.getElementById(id);
      if (el && t[key]) {
        el.innerHTML = t[key];
      }
    });

    // Update "Add Files" and dropzone labels
    const addFilesBtns = document.querySelectorAll('.add-files-btn-text');
    addFilesBtns.forEach(btn => {
      if (t.addFilesBtn) btn.textContent = t.addFilesBtn;
    });

    const dropTitles = document.querySelectorAll('.dropzone-title');
    if (dropTitles[0] && t.dropTitle) dropTitles[0].innerHTML = t.dropTitle;
    const dropSubtitles = document.querySelectorAll('.dropzone-subtitle');
    if (dropSubtitles[0] && t.dropSubtitle) dropSubtitles[0].textContent = t.dropSubtitle;

    // Update Sponsor Button text
    const coffeeText = document.querySelector('.coffee-text');
    if (coffeeText && t.supportBtn) coffeeText.textContent = t.supportBtn;

    // RTL for Arabic
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

  static init() {
    const saved = localStorage.getItem('optipixel_lang') || 'en';
    const select = document.getElementById('langSelect');
    if (select) {
      select.value = saved;
    }
    this.setLanguage(saved);
  }
}

window.I18nEngine = I18nEngine;
document.addEventListener('DOMContentLoaded', () => {
  I18nEngine.init();
});
